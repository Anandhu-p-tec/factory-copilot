"""Run eval/questions.json through the real HTTP pipeline (FastAPI TestClient) and write EVAL.md.

Checks per question:
  status      - did the system say supported / partial / none as a reviewer would?
  evidence    - does an evidence passage with the expected doc, page and text appear (citation correctness)?
  revision    - for superseded documents: answer evidence comes from the current revision, old one is flagged
  latency     - end-to-end /api/ask time
Run:  python eval/run_eval.py           (uses extractive mode unless GROQ_API_KEY is set)
"""
import json, os, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("FC_LOG", "0")
from fastapi.testclient import TestClient
from app.main import app

cases = json.loads((ROOT / "eval" / "questions.json").read_text())
client = TestClient(app)
health = client.get("/api/health").json()
rows, fails = [], 0
for c in cases:
    t0 = time.perf_counter()
    d = client.post("/api/ask", json={"question": c["q"]}).json()
    ms = (time.perf_counter() - t0) * 1000
    ev = [s for s in d["sources"] if s["role"] == "evidence"]
    old = [s for s in d["sources"] if s["role"] == "superseded"]
    status_ok = d["status"] == c["status"] or (c["status"] == "partial" and d["status"] == "conflict")
    ev_ok = True
    if c.get("expect"):
        ev_ok = all(any(s["doc_no"] == e["doc_no"] and s["page"] == e["page"] and e["contains"].lower() in s["text"].lower().replace("\n", " ")
                        or (s["doc_no"] == e["doc_no"] and s["page"] == e["page"] and e["contains"].lower() in s["text"].lower()) for s in ev)
                    for e in c["expect"])
    rev_ok = True
    if "revision" in c:
        rev_ok = bool(ev) and all(s["revision"] == f"Rev {c['revision']:02d}" for s in ev if s["doc_no"] == "QC-SOP-014")
    if not c.get("allow_old_revision") and any(s["doc_status"] == "superseded" for s in ev):
        rev_ok = False
    if c.get("expect_superseded_flag"):
        rev_ok = rev_ok and bool(old) and bool(d["warnings"])
    abstain_ok = True
    if c["status"] == "none":
        abstain_ok = d["status"] == "none" and not ev
    ok = status_ok and ev_ok and rev_ok and abstain_ok
    fails += (not ok)
    rows.append((c, d, ok, status_ok, ev_ok, rev_ok, ms, ev))

lines = ["# Evaluation results", "",
         f"Pipeline: `{health['embedder']}` retrieval, answer mode `{'llm' if health['llm_configured'] else 'extractive (no API key)'}`, "
         f"{health['documents']} documents, {health['chunks']} chunks. Generated by `python eval/run_eval.py`.", "",
         "| ID | Group | Question | Expected | Got | Evidence cited correctly | Revision handling | ms | Pass |", "|---|---|---|---|---|---|---|---|---|"]
for c, d, ok, s_ok, e_ok, r_ok, ms, ev in rows:
    cites = "; ".join(f"{s['doc_no']} {s['revision']} p{s['page']}" for s in ev[:3]) or "-"
    lines.append(f"| {c['id']} | {c['group']} | {c['q']} | {c['status']} | {d['status']} | {'yes' if e_ok else 'NO'} ({cites}) | {'ok' if r_ok else 'NO'} | {ms:.0f} | {'PASS' if ok else '**FAIL**'} |")
n = len(rows)
lines += ["", f"**{n - fails}/{n} passed.** Latency (retrieval + extractive answer, no LLM): "
          f"median {sorted(r[6] for r in rows)[n // 2]:.0f} ms, max {max(r[6] for r in rows):.0f} ms.", ""]
unans = [r for r in rows if r[0]["status"] == "none"]
lines.append(f"Unanswerable questions correctly refused: {sum(1 for r in unans if r[2])}/{len(unans)}.")
lines.append("")
lines.append("## Details for failures / notes")
for c, d, ok, *_ , ms, ev in rows:
    if not ok or c.get("note"):
        lines.append(f"- **{c['id']}** {'(FAIL) ' if not ok else ''}{c.get('note','')} Got `{d['status']}`; "
                     f"diagnostics {d['diagnostics']}; notes {d['notes']}")
Path(ROOT / "EVAL.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
sys.exit(1 if fails else 0)
